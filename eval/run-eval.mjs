// Scores the local engine against real GitHub-issue traces and blind labels.
// Run: node eval/run-eval.mjs   -> writes eval/RESULTS.md and eval/results-*.csv
import { readFileSync, writeFileSync, existsSync } from 'fs';
import { parseError } from '../src/engine/parser.js';
import { groundReport } from '../src/engine/grounding.js';
import { lintCommand } from '../src/engine/safety.js';

const dir = new URL('.', import.meta.url);
const load = (f) => JSON.parse(readFileSync(new URL(f, dir), 'utf8'));

const LOCAL_ENV = { Other: 'Terminal / Generic' };
const norm = (s) => (s || '').toLowerCase().replace(/[^a-z0-9]/g, '');
const base = (p) => (p || '').replace(/\\\\/g, '\\').split(/[\\/]/).pop().toLowerCase();
const splitLoc = (s) => {
  const m = (s || '').match(/^(.*?)(?::(\d+))?(?::\d+)?$/);
  return m ? [m[1], m[2]] : [s, undefined];
};
function locMatch(reported, expected) {
  if (!expected || expected === 'none') return true; // nothing to locate
  const [ef, el] = splitLoc(expected);
  const [rf, rl] = splitLoc(reported);
  return !!rf && base(rf) === base(ef) && (!el || el === rl);
}

function score(datasetFile, labelsFile) {
  const labels = new Map(load(labelsFile).map(l => [l.id, l]));
  const rows = [];
  for (const d of load(datasetFile)) {
    const label = labels.get(d.id);
    if (!label) continue;
    const r = parseError(d.trace);
    const g = groundReport(r, d.trace);
    const supported = label.environment !== 'Other';
    const envOk = r.environment === (LOCAL_ENV[label.environment] || label.environment);
    const typeOk = supported && (norm(r.errorType).includes(norm(label.errorType)) || norm(label.errorType).includes(norm(r.errorType)));
    const locOk = supported && locMatch(r.location, label.location);
    rows.push({
      id: d.id, category: d.category, usable: label.traceUsable !== false, supported,
      envOk, typeOk, locOk, correct: supported && envOk && typeOk && locOk,
      confidence: r.confidence, grounded: `${g.verified}/${g.total}`, fullyGrounded: g.verified === g.total,
      safety: lintCommand(r.fixCommand).level, hasFix: !!r.fixCommand,
      expected: `${label.environment} | ${label.errorType} | ${label.location}`,
      got: `${r.environment} | ${r.errorType} | ${r.location}`,
      source: d.source,
    });
  }
  const usable = rows.filter(r => r.usable);
  const sup = usable.filter(r => r.supported);
  const unsup = usable.filter(r => !r.supported);
  const wrong = sup.filter(r => !r.correct);
  const c = (arr, f) => arr.filter(f).length;
  return {
    rows, usable, sup, unsup, wrong,
    m: {
      total: rows.length,
      excluded: rows.length - usable.length,
      supported: sup.length,
      env: [c(sup, r => r.envOk), sup.length],
      type: [c(sup, r => r.typeOk), sup.length],
      loc: [c(sup, r => r.locOk), sup.length],
      all: [c(sup, r => r.correct), sup.length],
      wrongLow: [c(wrong, r => r.confidence === 'low'), wrong.length],
      unsupLow: [c(unsup, r => r.confidence === 'low'), unsup.length],
      confidentWrong: [[...wrong, ...unsup].filter(r => r.confidence !== 'low').length, usable.length],
      grounded: [c(usable, r => r.fullyGrounded), usable.length],
      danger: [c(usable, r => r.safety === 'danger'), c(usable, r => r.hasFix)],
    },
  };
}

const fmt = ([a, b]) => (b ? `${a}/${b} (${Math.round((100 * a) / b)}%)` : 'n/a');
const sets = [['Development', 'dataset.json', 'labels.json'], ['Held-out', 'heldout.json', 'heldout-labels.json']]
  .filter(([, d, l]) => existsSync(new URL(d, dir)) && existsSync(new URL(l, dir)))
  .map(([name, d, l]) => ({ name, ...score(d, l) }));

const row = (label, key) => `| ${label} | ${sets.map(s => fmt(s.m[key])).join(' | ')} |`;
const lines = [
  '# ErrorSpeak evaluation on real GitHub-issue errors',
  '',
  'Generated by `node eval/run-eval.mjs`. Do not edit by hand.',
  '',
  '## Method',
  '- Traces come from 15 fixed GitHub issue searches (`eval/collect.py`), newest first, created before 2026-10-01. Only issues whose body contains an extractable trace are kept. No hand-picking.',
  '- **Development set** (`dataset.json`): the first 5 such issues per search. The parser was improved after looking at its misses here, so these numbers are flattering.',
  '- **Held-out set** (`heldout.json`): the next 5 issues per search, collected after tuning stopped and scored once. These are the honest numbers.',
  '- Expected answers were labelled blind by a separate reviewer pass that saw only the trace text, never ErrorSpeak\'s output (`labels.json`, `heldout-labels.json`).',
  '- User-folder names and emails were masked before storage. No API keys or tokens were found in either set.',
  '- Traces cut off before the error message are excluded from the scores.',
  '- Before tuning, the development set scored 34/51 all correct with 12/66 confident-but-wrong answers (parser at commit 9c03d87).',
  '',
  '## Results (local engine only, no LLM)',
  '',
  `| Measure | ${sets.map(s => s.name).join(' | ')} |`,
  `|---|${sets.map(() => '---').join('|')}|`,
  `| Traces (excluded as cut off) | ${sets.map(s => `${s.m.total} (${s.m.excluded})`).join(' | ')} |`,
  `| Supported errors (Python, Node.js, Git, Docker) | ${sets.map(s => s.m.supported).join(' | ')} |`,
  row('Environment detected correctly', 'env'),
  row('Error type correct', 'type'),
  row('Location correct', 'loc'),
  row('All three correct', 'all'),
  row('Wrong answers that were marked low confidence', 'wrongLow'),
  row('Unsupported languages (Rust, Go, Java) marked low confidence', 'unsupLow'),
  row('**Confident but wrong** (the failure that matters)', 'confidentWrong'),
  row('Reports whose every claim was found in the trace', 'grounded'),
  row('Suggested commands rated destructive', 'danger'),
  '',
];
for (const s of sets) {
  const misses = [...s.wrong, ...s.unsup.filter(r => r.confidence !== 'low')];
  lines.push(`## Every miss: ${s.name.toLowerCase()} set`, '', '| id | expected | got | confidence |', '|---|---|---|---|',
    ...misses.map(r => `| [${r.id}](${r.source}) | ${r.expected} | ${r.got} | ${r.confidence} |`), '');
  const header = Object.keys(s.rows[0]);
  writeFileSync(new URL(`results-${s.name.toLowerCase()}.csv`, dir),
    [header.join(','), ...s.rows.map(r => header.map(h => JSON.stringify(r[h] ?? '')).join(','))].join('\n'));
}
writeFileSync(new URL('RESULTS.md', dir), lines.join('\n'));
